/** یافتن محتوای یک صنف. */
export function findIndustry(id: string | null | undefined): Industry | null {
  if (!id) return null;
  return INDUSTRIES.find((i) => i.id === id) ?? null;
}

/**
 * برچسب فارسی و ایموجی صنف از `business-types`.
 *
 * عمداً اینجا تکرار نمی‌شود: اگر برچسب در دو جا بود، روزی یکی عوض
 * می‌شد و فرم معارفه با سایت معرفی فرق می‌کرد.
 */
export function industryMeta(id: string): { label: string; emoji: string } | null {
  const type = BUSINESS_TYPES.find((t) => t.id === id);
  return type ? { label: type.label, emoji: type.emoji } : null;
}

/** صنف‌هایی که صفحه‌ی اختصاصی دارند (همه به‌جز «سایر»). */
export const INDUSTRY_IDS = INDUSTRIES.map((i) => i.id);
