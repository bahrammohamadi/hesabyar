/** جدیدترین نسخه‌ای که یادداشت دارد. */
export function latestRelease(): ReleaseNote | null {
  return RELEASES[0] ?? null;
}

/**
 * نسخه‌هایی که کاربر هنوز ندیده.
 *
 * @param lastSeen آخرین نسخه‌ای که کاربر یادداشتش را دیده
 *
 * ⚠️ مقایسه‌ی رشته‌ای انجام می‌شود نه عددی: قالب نسخه‌ها `yy.mmdd`
 * است که مرتب‌سازی رشته‌ای‌اش با ترتیب زمانی یکی است. اگر روزی به
 * `1.234` برگشتیم این فرض می‌شکند، پس به‌جای مقایسه، بر اساس *موقعیت*
 * در آرایه کار می‌کنیم که همیشه درست است.
 */
export function unseenReleases(lastSeen: string | null): ReleaseNote[] {
  if (!lastSeen) {
    /*
      کاربر تازه — فقط جدیدترین نشان داده می‌شود، نه کل تاریخچه.
      نمایش ۱۰ اعلان خوانده‌نشده به کسی که تازه ثبت‌نام کرده، بیشتر
      شبیه خرابی است تا خوش‌آمدگویی.
    */
    return RELEASES.slice(0, 1);
  }
  const index = RELEASES.findIndex((r) => r.version === lastSeen);
  // نسخه‌ی ناشناخته (مثلاً پس از rollback) → فقط جدیدترین
  if (index === -1) return RELEASES.slice(0, 1);
  return RELEASES.slice(0, index);
}
