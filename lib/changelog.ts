/**
 * یادداشت‌های انتشار — «در این نسخه چه چیزی عوض شد».
 *
 * چرا در کد و نه در دیتابیس؟
 *   این متن با خودِ نسخه می‌آید. اگر در دیتابیس بود، دو منبع حقیقت
 *   داشتیم: کدی که دیپلوی شده و رکوردی که ممکن است کسی یادش برود
 *   اضافه کند یا اشتباه بنویسد. اینجا در همان کامیتی که قابلیت را
 *   اضافه می‌کند، توضیحش هم نوشته می‌شود و در گیت می‌ماند.
 *
 *   اعلان‌های *سراسری* (مثل «فردا سرویس قطع است») همچنان از دیتابیس
 *   می‌آیند، چون بدون دیپلوی باید قابل انتشار باشند. زنگوله هر دو را
 *   کنار هم نشان می‌دهد.
 *
 * ⚠️ ترتیب مهم است: جدیدترین بالا. `date` به شکل `YYYY-MM-DD` میلادی
 * ذخیره می‌شود و در UI شمسی نمایش داده می‌شود.
 */

export type ChangeKind = "feature" | "fix" | "security" | "improvement";

export interface ChangeEntry {
  kind: ChangeKind;
  text: string;
}

export interface ReleaseNote {
  /** نسخه‌ای که این تغییرات در آن منتشر شد. */
  version: string;
  date: string;
  /** عنوان کوتاه برای نمایش در فهرست. */
  title: string;
  changes: ChangeEntry[];
}

