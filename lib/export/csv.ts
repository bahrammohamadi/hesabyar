/**
 * 🔴 CSV Injection (که به آن Formula Injection هم می‌گویند).
 *
 * نسخه‌ی قبلی فقط گیومه را دو برابر می‌کرد:
 *     `"${text.replace(/"/g, '""')}"`
 *
 * مشکل: اکسل و Google Sheets هر سلولی را که با `=`، `+`، `-`، `@`
 * یا کاراکترهای کنترلی تب/CR شروع شود **فرمول** تلقی می‌کنند —
 * حتی وقتی داخل گیومه باشد.
 *
 * سناریوی واقعی: کاربر کالایی به نام `=cmd|' /C calc'!A1` می‌سازد
 * (یا ما از فایل اکسل واردش می‌کنیم). بعد صاحب فروشگاه از کالاها
 * خروجی می‌گیرد و فایل را باز می‌کند. اکسل هشدار می‌دهد ولی خیلی‌ها
 * روی «فعال‌سازی» کلیک می‌کنند و آن فرمول روی *کامپیوتر او* اجرا
 * می‌شود.
 *
 * (بازتولید شد: `csvEscape("=cmd|@ calc!A1")` دقیقاً همان رشته را
 * با گیومه برمی‌گرداند و اکسل آن را فرمول می‌بیند.)
 *
 * راه‌حل استاندارد (همان کاری که OWASP توصیه می‌کند و ابزارهای بزرگ
 * انجام می‌دهند): پیش از کاراکتر خطرناک یک آپاستروف می‌گذاریم. اکسل
 * آپاستروف ابتدایی را نمایش نمی‌دهد ولی سلول را «متن» می‌کند.
 *
 * ⚠️ چرا عدد منفی مشکلی ندارد: شرط فقط وقتی برقرار است که کاراکتر
 * بعدی رقم نباشد. یعنی `-15000` دست‌نخورده می‌ماند ولی `-cmd|...`
 * خنثی می‌شود. بدون این استثنا، همه‌ی مبالغ منفی در اکسل به متن
 * تبدیل می‌شدند و جمع‌بستن‌شان کار نمی‌کرد.
 */
export function csvEscape(value: unknown): string {
  const text = value == null ? "" : String(value);

  const dangerous = /^[=+@\t\r]/.test(text) || /^-(?![\d.])/.test(text);
  const safe = dangerous ? `'${text}` : text;

  return `"${safe.replace(/"/g, '""')}"`;
}

/**
 * متن کامل CSV از ردیف‌ها.
 *
 * سرستون‌ها از کلیدهای *اولین* ردیف گرفته می‌شوند، پس همه‌ی ردیف‌ها
 * باید ساختار یکسان داشته باشند.
 *
 * BOM (`\ufeff`) در ابتدا الزامی است: بدون آن، اکسل روی ویندوز فایل
 * را با کدگذاری محلی می‌خواند و **تمام متن فارسی به هم می‌ریزد**.
 */
export function buildCsv(rows: Record<string, unknown>[]): string {
  if (rows.length === 0) return "\ufeff";
  const headers = Object.keys(rows[0]);
  const lines = [
    headers.map(csvEscape).join(","),
    ...rows.map((row) => headers.map((header) => csvEscape(row[header])).join(",")),
  ];
  /*
    جداکننده‌ی سطر CRLF است نه LF.
    طبق RFC 4180 و مهم‌تر از آن، اکسل روی ویندوز با LF تنها گاهی
    همه‌ی سطرها را در یک خط می‌چسباند.
  */
  return "\ufeff" + lines.join("\r\n");
}

/** نام فایل امن — کاراکترهای غیرمجاز سیستم‌عامل حذف می‌شوند. */
export function safeFilename(name: string): string {
  return name
    .replace(/[\\/:*?"<>|]/g, "-")
    .replace(/\s+/g, "-")
    .slice(0, 120);
}
