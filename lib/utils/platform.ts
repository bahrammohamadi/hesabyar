/**
 * تشخیص پلتفرم — فقط برای جاهایی که رفتار مرورگر واقعاً فرق می‌کند.
 *
 * ⚠️ تشخیص از روی `userAgent` معمولاً کار درستی نیست و باید سراغ
 * «تشخیص قابلیت» رفت. ولی محدودیت‌های مجوز رسانه در iOS **رفتاری**اند
 * نه قابلیتی: هیچ پرچمی وجود ندارد که بگوید «این مرورگر مجوز را فقط
 * داخل ژست کاربر می‌دهد». تنها راه، همین است.
 *
 * چرا ماژول جدا؟
 *   هم بارکدخوان (دوربین) و هم ورود صوتی (میکروفون) به آن نیاز دارند.
 *   وارد کردن یکی از دیگری، وابستگی بی‌ربط می‌سازد: صفحه‌ای که فقط
 *   بارکد می‌خواند، کل منطق تشخیص گفتار را هم در باندل می‌آورد.
 */

/**
 * آیا روی iOS اجرا می‌شویم؟
 *
 * ⚠️ آیپد از iPadOS 13 به بعد خودش را «Macintosh» معرفی می‌کند تا
 * سایت‌ها نسخه‌ی دسکتاپ بدهند. تنها نشانه‌ی باقی‌مانده، وجود صفحه‌ی
 * لمسی است — مک‌بوک `ontouchend` ندارد.
 */
export function isIOS(): boolean {
  if (typeof navigator === "undefined") return false;
  const ua = navigator.userAgent;
  return (
    /iPad|iPhone|iPod/.test(ua) ||
    (/Macintosh/.test(ua) && typeof document !== "undefined" && "ontouchend" in document)
  );
}

/**
 * آیا داخل مرورگرِ درون‌برنامه‌ای هستیم (اینستاگرام، تلگرام، …)؟
 *
 * 🔴 برای کاربران ایرانی حیاتی است: بیشترشان لینک را از اینستاگرام یا
 * تلگرام باز می‌کنند. در `WKWebView` روی iOS، `webkitSpeechRecognition`
 * *وجود دارد* — پس هر بررسی قابلیتی می‌گوید «پشتیبانی می‌شود» — ولی
 * `start()` بی‌صدا شکست می‌خورد. بدترین حالت ممکن: دکمه هست، کاربر
 * می‌زند، هیچ اتفاقی نمی‌افتد و هیچ خطایی هم داده نمی‌شود.
 *
 * دوربین هم در همین محیط‌ها اغلب مسدود است.
 */
export function isInAppBrowser(): boolean {
  if (typeof navigator === "undefined") return false;
  // FBAN/FBAV: اپ‌های متا (فیسبوک و اینستاگرام)
  return /FBAN|FBAV|Instagram|Line\/|Telegram|WhatsApp|Twitter|MicroMessenger/i.test(
    navigator.userAgent
  );
}

/**
 * راهنمای بازیابی مجوز، متناسب با همان دستگاه.
 *
 * 🔴 چرا لازم شد: پیام قبلی می‌گفت «روی آیکون قفل کنار نشانی سایت
 * بزنید». در سافاری آیفون **چنین آیکونی وجود ندارد**؛ کاربر دنبال
 * چیزی می‌گشت که نبود و هیچ کاری از دستش برنمی‌آمد. مسیر واقعی آیفون
 * از دکمه‌ی «aA» در نوار نشانی می‌گذرد.
 */
export function permissionHelp(kind: "camera" | "microphone"): {
  variant: "in-app" | "ios" | "default";
  steps: string[];
  note?: string;
} {
  const fa = kind === "camera" ? "دوربین" : "میکروفون";
  const en = kind === "camera" ? "Camera" : "Microphone";

  if (isInAppBrowser()) {
    return {
      variant: "in-app",
      steps: [
        "روی «…» یا «Share» در گوشه‌ی صفحه بزنید",
        "گزینه‌ی «Open in Safari» یا «باز کردن در مرورگر» را انتخاب کنید",
        `در مرورگر اصلی دوباره ${fa} را امتحان کنید`,
      ],
      note: `${fa} در مرورگرِ داخل اینستاگرام و تلگرام کار نمی‌کند.`,
    };
  }

  if (isIOS()) {
    /*
      🔴 «بالای صفحه» غلط بود.

      از iOS 15 نوار نشانی سافاری به‌صورت پیش‌فرض **پایین** صفحه است.
      کاربر با اسکرین‌شات نشان داد که دنبال دکمه‌ای در بالای صفحه
      می‌گشت که آنجا نبود. حالا جهت ذکر نمی‌شود و به‌جایش نشانه‌ی
      بصری داده می‌شود که در هر دو چیدمان صدق می‌کند.

      نکته‌ی دوم از همان اسکرین‌شات: وقتی سافاری میکروفون را مسدود
      می‌کند، یک آیکون میکروفونِ خط‌خورده کنار نشانی سایت می‌گذارد.
      همان آیکون کوتاه‌ترین راه است — زدنش مستقیم به تنظیمات سایت
      می‌برد. این را اول می‌گوییم.
    */
    const icon = kind === "microphone" ? "میکروفون خط‌خورده 🎙️" : "دوربین خط‌خورده";
    return {
      variant: "ios",
      steps: [
        `اگر آیکون ${icon} کنار نشانی سایت می‌بینید، روی همان بزنید`,
        "در غیر این صورت روی «aA» یا آیکون کنار نشانی بزنید (در آیفون معمولاً پایین صفحه است)",
        "«Website Settings» را انتخاب کنید",
        `«${en}» را روی «Allow» بگذارید و صفحه را تازه کنید`,
      ],
      note: `اگر باز هم نشد: تنظیمات آیفون ← Safari ← ${en} ← Allow`,
    };
  }

  return {
    variant: "default",
    steps: [
      "روی آیکون قفل 🔒 کنار نشانی سایت در نوار مرورگر بزنید",
      `گزینه‌ی «${fa}» (${en}) را پیدا کنید`,
      "آن را روی «اجازه دادن» (Allow) بگذارید",
      "صفحه را یک‌بار تازه‌سازی کنید",
    ],
    note: `در سافاری دسکتاپ: منوی Safari ← Settings for This Website ← ${en} ← Allow`,
  };
}
