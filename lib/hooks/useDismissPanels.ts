"use client";

import { useEffect } from "react";
import { usePanelManager } from "@/src/core/panel-manager/panel-manager.store";

/**
 * وقتی یک پنجره‌ی مودال باز می‌شود، پنل‌های کشویی باز را می‌بندد.
 *
 * مشکلی که در اصل حل می‌کرد:
 *   پروژه دو سیستم لایه‌ای مستقل دارد که از هم خبر ندارند —
 *   PanelManager (کشوی کناری) و Modal (پنجره‌ی وسط صفحه).
 *   کلیک روی «نمای سریع» داخل یک کشو، مودال را روی کشو باز می‌کرد و
 *   کشوی قبلی همان‌جا می‌ماند: دو لایه‌ی رقیب روی هم.
 *
 * 🔴 باگی که این رفتار ساخت:
 *   فرم «فروش جدید» خودش داخل یک پنل رندر می‌شود. وقتی کاربر روی
 *   «افزودن سریع» یا نوار جستجوی کالا می‌زد، ProductSelector یک Modal
 *   باز می‌کرد → closeAll() اجرا می‌شد → *همان پنلی که فرم داخلش بود*
 *   نابود می‌شد. کل فاکتور نیمه‌کاره از بین می‌رفت.
 *   (بازتولیدشده: dialogs=1 → 0 و پاک‌شدن ?panels= از URL)
 *
 *   ریشه: هوک نمی‌توانست دو حالت را از هم تشخیص دهد —
 *     الف) مودالی که *جایگزین* پنل می‌شود (باید ببندد)
 *     ب) مودالی که *فرزند* پنل است، مثل انتخابگر کالا (نباید ببندد)
 *
 * راه‌حل: پارامتر `owned`. مودال‌هایی که از دل یک پنل باز می‌شوند و
 * قرار است پس از بسته‌شدن، کاربر را به همان پنل برگردانند، با
 * `owned = true` علامت می‌خورند و از این رفتار مستثنا می‌شوند.
 *
 * پیش‌فرض `false` است تا رفتار قبلی برای بقیه‌ی مودال‌ها حفظ شود.
 *
 * @param active آیا مودال هم‌اکنون باز است.
 * @param owned  آیا این مودال متعلق به پنل باز است (انتخابگر داخل فرم).
 */
export function useDismissPanels(active: boolean, owned = false) {
  const { closeAll, stack } = usePanelManager();

  useEffect(() => {
    if (owned) return;
    if (active && stack.length > 0) closeAll();
    // فقط به تغییر «باز شدن» واکنش نشان می‌دهیم، نه به تغییر خود stack،
    // وگرنه بستن دستی یک پنل دوباره این افکت را اجرا می‌کند.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [active, owned]);
}
