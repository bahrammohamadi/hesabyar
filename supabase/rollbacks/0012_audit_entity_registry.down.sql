-- Hesabyar Rollback 0012 - بازگشت غیرمخرب زیرساخت Audit/Registry
-- نوع: DOWN migration دستی و ایمن
-- سیاست ایمنی: هیچ داده‌ای حذف نمی‌شود.
-- بنابراین audit_logs و entity_registry عمداً DROP/TRUNCATE نمی‌شوند.
-- =============================================================

-- -------------------------------------------------------------
-- ۱) حذف اتصال trigger لازم نیست چون در UP هیچ triggerی به جدول‌ها وصل نشده است.
-- اگر در آینده triggerها وصل شدند، ابتدا باید با DROP TRIGGER IF EXISTS جداگانه جدا شوند.
-- -------------------------------------------------------------

-- -------------------------------------------------------------
-- ۲) حذف تابع عمومی audit
-- این کار داده audit_logs را حذف نمی‌کند.
-- اگر triggerی در آینده به این تابع وصل شده باشد، این دستور fail می‌شود تا از خرابی پنهان جلوگیری کند.
-- -------------------------------------------------------------
drop function if exists public.fn_audit_trigger();

-- -------------------------------------------------------------
-- ۳) حذف policy خواندن registry
-- داده entity_registry حذف نمی‌شود.
-- -------------------------------------------------------------
drop policy if exists entity_registry_select_authenticated on public.entity_registry;

-- -------------------------------------------------------------
-- ۴) حذف ایندکس‌های audit در صورت نیاز rollback فنی
-- این کار داده audit_logs را حذف نمی‌کند؛ فقط ایندکس‌ها حذف می‌شوند.
-- -------------------------------------------------------------
drop index if exists public.idx_audit_logs_entity;
drop index if exists public.idx_audit_logs_created_at_desc;

-- -------------------------------------------------------------
-- ۵) افزونه‌ها حذف نمی‌شوند.
-- دلیل: ممکن است pgcrypto/pg_trgm توسط بخش‌های دیگر دیتابیس استفاده شوند.
-- -------------------------------------------------------------

-- -------------------------------------------------------------
-- ۶) جداول audit_logs و entity_registry حذف نمی‌شوند.
-- دلیل: حذف آن‌ها داده audit/registry را پاک می‌کند و خلاف قانون No Data Loss است.
-- اگر rollback کامل و مخرب لازم شد، باید بعد از backup و تأیید دستی جداگانه انجام شود.
-- -------------------------------------------------------------

