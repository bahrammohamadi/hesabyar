with updated as (
  update public.contacts c
  set
    name = coalesce(nullif(t.full_name, ''), c.name),
    phone = t.phone,
    meta = coalesce(c.meta, '{}'::jsonb)
      || jsonb_build_object(
        'first_name', nullif(t.first_name, ''),
        'last_name', nullif(t.last_name, ''),
        'birth_date', nullif(t.birth_date, ''),
        'mobile', t.phone,
        'extra_phone', nullif(t.extra_phone, ''),
        'source_pdf_raw_line', nullif(t.raw_line, '')
      ),
    updated_at = now()
  from tmp_contacts_pdf_import t
  where c.org_id = 'ec60535d-6372-428a-92fe-06f1eb63f4b7'::uuid
    and regexp_replace(coalesce(c.phone,''), '\D', '', 'g') = regexp_replace(t.phone, '\D', '', 'g')
  returning c.id
), membership_fix as (
  insert into public.memberships(org_id, branch_id, user_id, role, is_active, created_by)
  select 'ec60535d-6372-428a-92fe-06f1eb63f4b7'::uuid,
         'a4e596ac-92a1-42d3-beb0-a72964edc8dd'::uuid,
         u.id,
         'owner',
         true,
         (select id from auth.users where lower(email)='bahram@hesabyar.app' limit 1)
  from auth.users u
  where lower(u.email)='09111558263@hesabyar.app'
  and not exists (
    select 1 from public.memberships m
    where m.user_id=u.id and m.org_id='ec60535d-6372-428a-92fe-06f1eb63f4b7'::uuid
  )
  returning id
), membership_deactivated as (
  update public.memberships m
  set is_active=false
  from auth.users u
  where m.user_id=u.id
    and lower(u.email)='09111558263@hesabyar.app'
    and m.org_id <> 'ec60535d-6372-428a-92fe-06f1eb63f4b7'::uuid
  returning m.id
)
select (select count(*) from updated) as updated_contacts,
       (select count(*) from membership_fix) as inserted_main_memberships_for_phone_user,
